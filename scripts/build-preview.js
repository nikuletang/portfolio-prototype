// Builds single self-contained copies of each page with the CSS and JS
// inlined, so they render in viewers that open one file only.
//   index.html               → preview.html        (DC Water)
//   grove-family-health.html → grove-preview.html  (Grove Family Health)
// Usage: node scripts/build-preview.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8");

const pages = [
  ["index.html", "preview.html"],
  ["grove-family-health.html", "grove-preview.html"],
];

for (const [src, out] of pages) {
  let html = read(src);
  html = html.replace(/<link rel="stylesheet" href="(css\/[\w-]+\.css)">/g, (_, f) => "<style>\n" + read(f) + "\n</style>");
  html = html.replace(/<script src="(js\/[\w-]+\.js)"><\/script>/g, (_, f) => "<script>\n" + read(f) + "\n</script>");
  html = html.replace("<head>", `<head>\n  <!-- GENERATED by scripts/build-preview.js from ${src}. Edit the source files, not this one. -->`);
  fs.writeFileSync(path.join(root, out), html);
  console.log("Wrote " + out + " (" + Math.round(html.length / 1024) + " KB)");
}
