// Builds preview.html: a single self-contained copy of index.html with the
// CSS and JS inlined, so it renders in viewers that open one file only.
// Usage: node scripts/build-preview.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8");

let html = read("index.html");
html = html.replace(
  '<link rel="stylesheet" href="css/styles.css">',
  () => "<style>\n" + read("css/styles.css") + "\n</style>"
);
for (const f of ["js/config.js", "js/assets.js", "js/main.js"]) {
  html = html.replace(`<script src="${f}"></script>`, () => "<script>\n" + read(f) + "\n</script>");
}
html = html.replace("<head>", "<head>\n  <!-- GENERATED by scripts/build-preview.js from index.html. Edit the source files, not this one. -->");
fs.writeFileSync(path.join(root, "preview.html"), html);
console.log("Wrote preview.html (" + Math.round(html.length / 1024) + " KB)");
